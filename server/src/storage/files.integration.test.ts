import { createHash, randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import Fastify from 'fastify';
import sensible from '@fastify/sensible';
import { describe, expect, it } from 'vitest';
import { loadConfig } from '../config.js';
import { PostgresDatabase } from '../database/postgres.js';
import { PostgresAccountRepository } from '../repositories/postgres-account-repository.js';
import { registerRoutes } from '../routes.js';
import { registerRuntimeRoutes } from '../runtime/routes.js';
import { roomRegistry } from '../runtime/registry.js';
import { RuntimeTools } from '../runtime/tools.js';
import { ToolGateway } from '../runtime/tool-gateway.js';
import { ShortTermMemoryService } from '../memories/short-term.js';
import { ObjectStore } from './object-store.js';

const config = loadConfig();
const dbCase = config.databaseUrl ? it : it.skip;

describe('real conversation files and cross-device handoff', () => {
  dbCase('uploads, attaches, previews and transfers artifacts with strict membership and retry checks', async () => {
    const schema = `kla_files_test_${randomUUID().replaceAll('-', '')}`;
    const database = new PostgresDatabase(config.databaseUrl, schema);
    const pool = database.rawPool!;
    const root = await mkdtemp(join(tmpdir(), 'kla-files-test-'));
    const app = Fastify();
    try {
      await database.migrate(schema);
      await app.register(sensible);
      const store = new ObjectStore(root);
      const accounts = new PostgresAccountRepository(pool);
      const worker = { kick() {}, cancel() {} };
      await registerRoutes(app, { accounts, database, objectStore: store, objectStorageMaxFileBytes: 1024, loopWorker: worker });
      await registerRuntimeRoutes(app, { pool, accounts, worker: worker as never, objectStore: store });
      const owner = await accounts.register({ email: 'files-owner@example.test', nickname: '文件拥有者', password: 'TestPass2026!' });
      const other = await accounts.register({ email: 'files-member@example.test', nickname: '群聊成员', password: 'TestPass2026!' });
      const outsider = await accounts.register({ email: 'files-outsider@example.test', nickname: '外部用户', password: 'TestPass2026!' });
      const enterprise = await accounts.createOrganization(owner.user.id, '文件协作企业', 'files-test-license');
      const invite = (await pool.query('SELECT invite_code FROM organizations WHERE id=$1', [enterprise.organizationId])).rows[0].invite_code;
      const member = (await accounts.joinOrganization(other.user.id, invite))!;
      const session = await accounts.createSession(owner.user.id);
      const otherSession = await accounts.createSession(other.user.id);
      const outsiderSession = await accounts.createSession(outsider.user.id);
      const headers = { authorization: `Bearer ${session.accessToken}`, 'x-identity-id': enterprise.id };
      const memberHeaders = { authorization: `Bearer ${otherSession.accessToken}`, 'x-identity-id': member.id };
      const outsiderHeaders = { authorization: `Bearer ${outsiderSession.accessToken}`, 'x-identity-id': outsider.identity.id };
      const personalHeaders = { ...headers, 'x-identity-id': owner.identity.id };
      const project = await accounts.createProject(enterprise.id, '共享项目');
      const room = await accounts.createConversation(project.id, '文件群聊');
      const otherRoom = await accounts.createConversation(project.id, '另一个群聊');
      await pool.query("INSERT INTO project_members(project_id,identity_id,role) VALUES($1,$2,'member')", [project.id, member.id]);
      await pool.query('INSERT INTO conversation_members(conversation_id,project_id,identity_id) VALUES($1,$2,$3)', [room.id, project.id, member.id]);
      const agent = (await roomRegistry(pool, room.id)).find(item => item.name === '本地执行智能体')!;
      const bytes = Buffer.from('# 共享附件\n实际上传内容');
      const checksum = createHash('sha256').update(bytes).digest('hex');
      const createUpload = async (payload: Record<string, unknown> = {}) => app.inject({ method: 'POST', url: '/api/v1/files/upload-sessions', headers, payload: { conversationId: room.id, fileName: 'source.md', contentType: 'text/markdown', sizeBytes: bytes.length, checksum, ...payload } });
      const created = await createUpload();
      expect(created.statusCode, created.body).toBe(201);
      const uploadId = created.json().data.id;
      const putUrl = `/api/v1/files/upload-sessions/${uploadId}/content`;
      const completeUrl = `/api/v1/files/upload-sessions/${uploadId}/complete`;
      expect((await app.inject({ method: 'POST', url: completeUrl, headers })).statusCode).toBe(409);
      expect((await app.inject({ method: 'PUT', url: putUrl, headers: { ...headers, 'content-type': 'application/octet-stream' }, payload: Buffer.from('bad') })).statusCode).toBe(409);
      expect((await app.inject({ method: 'PUT', url: putUrl, headers: { ...memberHeaders, 'content-type': 'application/octet-stream' }, payload: bytes })).statusCode).toBe(404);
      expect((await app.inject({ method: 'PUT', url: putUrl, headers: { ...headers, 'content-type': 'application/octet-stream' }, payload: bytes })).statusCode).toBe(200);
      const completed = await Promise.all([1, 2, 3].map(() => app.inject({ method: 'POST', url: completeUrl, headers })));
      completed.forEach(response => expect([200, 201], response.body).toContain(response.statusCode));
      const file = completed[0].json().data;
      expect(new Set(completed.map(response => response.json().data.id)).size).toBe(1);
      expect(file.checksum).toBe(checksum);
      expect(Number((await pool.query('SELECT count(*) FROM files WHERE storage_key=$1', [file.storageKey])).rows[0].count)).toBe(1);
      expect((await app.inject({ method: 'PUT', url: putUrl, headers: { ...headers, 'content-type': 'application/octet-stream' }, payload: bytes })).statusCode).toBe(409);
      for (const deniedHeaders of [personalHeaders, outsiderHeaders]) {
        expect((await app.inject({ method: 'GET', url: file.contentUrl, headers: deniedHeaders })).statusCode).toBe(404);
        expect((await app.inject({ method: 'GET', url: `/api/v1/files/${file.id}`, headers: deniedHeaders })).statusCode).toBe(404);
      }
      expect((await app.inject({ method: 'GET', url: file.contentUrl })).statusCode).toBe(401);
      const shared = await app.inject({ method: 'GET', url: file.contentUrl, headers: memberHeaders });
      expect(shared.statusCode).toBe(200); expect(shared.rawPayload).toEqual(bytes);
      expect((await app.inject({ method: 'GET', url: `/api/v1/files?conversationId=${room.id}`, headers: memberHeaders })).json().data).toHaveLength(1);
      const wrongScope = await app.inject({ method: 'POST', url: `/api/v1/conversations/${otherRoom.id}/messages`, headers, payload: { text: 'bad', fileIds: [file.id] } });
      expect(wrongScope.statusCode).toBe(403);
      const sent = await app.inject({ method: 'POST', url: `/api/v1/conversations/${room.id}/messages`, headers, payload: { fileIds: [file.id] } });
      expect(sent.statusCode, sent.body).toBe(200);
      expect(sent.json().data.message.metadata.files[0].id).toBe(file.id);
      const message = sent.json().data.message, run = sent.json().data.run;
      expect((await app.inject({ method: 'GET', url: `/api/v1/conversations/${room.id}/messages`, headers: memberHeaders })).json().data[0].metadata.fileIds).toEqual([file.id]);
      const memory = new ShortTermMemoryService(pool);
      const tools = new RuntimeTools(pool, accounts, memory, '', store);
      const scope = { identityId: enterprise.id, conversationId: room.id, agentId: agent.id };
      expect(await tools.execute('file_read', { fileId: file.id }, scope)).toMatchObject({ content: bytes.toString() });
      await expect(tools.execute('file_read', { fileId: file.id }, { ...scope, conversationId: otherRoom.id })).rejects.toThrow('当前群聊');
      const gateway = new ToolGateway(pool, tools, undefined, memory);
      const history = await gateway.conversationHistory(scope, message.id);
      expect(history.some(item => item.content?.includes(file.id))).toBe(true);
      const badMetadata = await accounts.createMessage(room.id, owner.user.id, '旧记录', { files: 'invalid' });
      await expect(gateway.conversationHistory(scope, badMetadata.id)).resolves.toBeDefined();
      const step = (await pool.query('INSERT INTO conversation_run_steps(run_id,step_index,title,instruction,assigned_agent_id) VALUES($1,1,$2,$3,$4) RETURNING id', [run.id, '处理共享文件', '读取后发布', agent.id])).rows[0];
      const registerDevice = async (name: string) => (await app.inject({ method: 'POST', url: '/api/v1/runtime/devices', headers, payload: { installationId: randomUUID(), name, platform: 'win32', capabilities: ['local_file_fetch', 'local_file_publish'] } })).json().data.id;
      const deviceA = await registerDevice('设备甲'), deviceB = await registerDevice('设备乙');
      await pool.query("UPDATE conversation_runs SET status='waiting_tool' WHERE id=$1", [run.id]);
      const createCall = async (tool: string, args: object, deviceId: string) => (await pool.query('INSERT INTO runtime_tool_calls(step_id,identity_id,device_id,model_call_id,tool_name,arguments) VALUES($1,$2,$3,$4,$5,$6) RETURNING id', [step.id, enterprise.id, deviceId, randomUUID(), tool, JSON.stringify(args)])).rows[0].id;
      const fetchCall = await createCall('local_file_fetch', { fileId: file.id }, deviceB);
      expect((await app.inject({ method: 'POST', url: `/api/v1/runtime/devices/${deviceB}/poll`, headers })).json().data.call.id).toBe(fetchCall);
      const inputUrl = `/api/v1/runtime/devices/${deviceB}/calls/${fetchCall}/input`;
      const downloaded = await app.inject({ method: 'GET', url: inputUrl, headers });
      expect(downloaded.statusCode, downloaded.body).toBe(200); expect(downloaded.rawPayload).toEqual(bytes);
      expect(downloaded.headers['x-kla-checksum']).toBe(checksum);
      expect((await app.inject({ method: 'GET', url: `/api/v1/runtime/devices/${deviceA}/calls/${fetchCall}/input`, headers })).statusCode).toBe(404);
      const anotherSession = await accounts.createSession(owner.user.id);
      expect((await app.inject({ method: 'GET', url: inputUrl, headers: { ...headers, authorization: `Bearer ${anotherSession.accessToken}` } })).statusCode).toBe(404);
      const approval = { approved: true, decidedAt: new Date().toISOString() };
      const receiptUrl = (deviceId: string, callId: string) => `/api/v1/runtime/devices/${deviceId}/calls/${callId}/receipt`;
      expect((await app.inject({ method: 'POST', url: receiptUrl(deviceB, fetchCall), headers, payload: { receiptId: randomUUID(), status: 'completed', result: { downloaded: true }, approval } })).statusCode).toBe(200);
      expect((await app.inject({ method: 'GET', url: inputUrl, headers })).statusCode).toBe(404);
      const publishCall = await createCall('local_file_publish', { path: 'workspace://runs/report.pdf' }, deviceA);
      expect((await app.inject({ method: 'POST', url: `/api/v1/runtime/devices/${deviceA}/poll`, headers })).json().data.call.id).toBe(publishCall);
      const resultBytes = Buffer.from('%PDF-1.4 shared result');
      const receipt = { receiptId: randomUUID(), status: 'completed', result: { uploaded: true }, approval, artifact: { fileName: 'report.pdf', mimeType: 'application/pdf', contentEncoding: 'base64', content: resultBytes.toString('base64'), checksum: createHash('sha256').update(resultBytes).digest('hex') } };
      const published = await app.inject({ method: 'POST', url: receiptUrl(deviceA, publishCall), headers, payload: receipt });
      expect(published.statusCode, published.body).toBe(200);
      const artifactId = published.json().data.artifactId;
      expect((await app.inject({ method: 'POST', url: receiptUrl(deviceA, publishCall), headers, payload: receipt })).json().data.artifactId).toBe(artifactId);
      const artifacts = await accounts.listArtifacts(member.id, room.id);
      expect(artifacts).toHaveLength(1); expect(artifacts[0].storageKey).toBeTruthy(); expect(artifacts[0].content).toBe('');
      expect((await app.inject({ method: 'GET', url: `/api/v1/artifacts/${artifactId}/content`, headers: memberHeaders })).rawPayload).toEqual(resultBytes);
      expect((await app.inject({ method: 'GET', url: `/api/v1/artifacts/${artifactId}/download`, headers: memberHeaders })).rawPayload).toEqual(resultBytes);
      expect((await app.inject({ method: 'GET', url: `/api/v1/artifacts/${artifactId}/download`, headers: personalHeaders })).statusCode).toBe(404);
      const artifactFetch = await createCall('local_file_fetch', { artifactId }, deviceB);
      await app.inject({ method: 'POST', url: `/api/v1/runtime/devices/${deviceB}/poll`, headers });
      const artifactInput = await app.inject({ method: 'GET', url: `/api/v1/runtime/devices/${deviceB}/calls/${artifactFetch}/input`, headers });
      expect(artifactInput.rawPayload).toEqual(resultBytes);
      expect(artifactInput.headers['x-kla-checksum']).toBe(receipt.artifact.checksum);
      const serverWrite = await createCall('artifact_write', { fileName: 'large.md', content: 'x'.repeat(300 * 1024) }, deviceA);
      const writeScope = { ...scope, toolCallId: serverWrite };
      const writeArgs = { fileName: 'large.md', content: 'x'.repeat(300 * 1024), mimeType: 'text/markdown' };
      const writeResults = await Promise.all([1, 2, 3].map(() => tools.execute('artifact_write', writeArgs, writeScope))) as Array<{ artifactId: string; storageKey: string }>;
      expect(new Set(writeResults.map(item => item.artifactId)).size).toBe(1);
      expect(new Set(writeResults.map(item => item.storageKey)).size).toBe(1);
      expect((await store.get(writeResults[0].storageKey))?.toString()).toBe(writeArgs.content);
      await expect(tools.execute('artifact_write', { ...writeArgs, content: 'changed' }, writeScope)).rejects.toThrow('不可覆盖');
      expect((await store.get(writeResults[0].storageKey))?.toString()).toBe(writeArgs.content);
      await pool.query("UPDATE conversation_runs SET status='completed' WHERE id=$1", [run.id]);
      const statusUrl = `/api/v1/runtime/devices/${deviceB}/workspaces/status`;
      expect((await app.inject({ method: 'POST', url: statusUrl, headers, payload: { runIds: [run.id, randomUUID()] } })).json().data).toEqual([{ runId: run.id, status: 'completed' }]);
      expect((await app.inject({ method: 'POST', url: statusUrl, headers: personalHeaders, payload: { runIds: [run.id] } })).statusCode).toBe(404);
      await pool.query('DELETE FROM conversation_members WHERE conversation_id=$1 AND identity_id=$2', [room.id, member.id]);
      expect((await app.inject({ method: 'GET', url: file.contentUrl, headers: memberHeaders })).statusCode).toBe(404);
      expect((await app.inject({ method: 'GET', url: `/api/v1/artifacts/${artifactId}/content`, headers: memberHeaders })).statusCode).toBe(404);
      expect((await createUpload({ sizeBytes: 1025 })).statusCode).toBe(413);
      expect((await createUpload({ fileName: '../escape' })).statusCode).toBe(400);
      const expired = await createUpload();
      await pool.query("UPDATE upload_sessions SET expires_at=now()-interval '1 second' WHERE id=$1", [expired.json().data.id]);
      expect((await app.inject({ method: 'POST', url: `/api/v1/files/upload-sessions/${expired.json().data.id}/complete`, headers })).statusCode).toBe(410);
      const mismatch = await createUpload({ checksum: '0'.repeat(64) });
      expect((await app.inject({ method: 'PUT', url: `/api/v1/files/upload-sessions/${mismatch.json().data.id}/content`, headers: { ...headers, 'content-type': 'application/octet-stream' }, payload: bytes })).statusCode).toBe(409);
      const empty = await createUpload({ fileName: 'empty.txt', sizeBytes: 0, checksum: createHash('sha256').update('').digest('hex') });
      const emptyId = empty.json().data.id;
      expect((await app.inject({ method: 'PUT', url: `/api/v1/files/upload-sessions/${emptyId}/content`, headers: { ...headers, 'content-type': 'application/octet-stream' }, payload: Buffer.alloc(0) })).statusCode).toBe(200);
      expect((await app.inject({ method: 'POST', url: `/api/v1/files/upload-sessions/${emptyId}/complete`, headers })).json().data.sizeBytes).toBe(0);
    } finally {
      await app.close();
      await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      await database.close();
      await rm(root, { recursive: true, force: true });
    }
  }, 45000);
});
